//Write JavaScript programs using different array methods instead of loops.

let arrayMethod=["apple","orange",true,120,"car","book"];

console.log(arrayMethod);

//push()-add at end
arrayMethod.push("pen");
console.log(arrayMethod);

//pop()-remove from end
arrayMethod.pop()
console.log(arrayMethod);

//unshift()-add at beginning
arrayMethod.unshift("mango")
console.log(arrayMethod);

//shift()-remove from beginning
arrayMethod.shift();
console.log(arrayMethod);

//includes-check the value present or not
arrayMethod.includes("apple")
console.log(arrayMethod);

//indexof()
arrayMethod.indexOf("car");
console.log(arrayMethod);

//join()-convert array to string
arrayMethod.join("");
console.log(arrayMethod);

//reverse()- reverse array
arrayMethod.reverse();
console.log(arrayMethod);

//sort()-sort array alphabetical order
arrayMethod.sort();
console.log(arrayMethod);











